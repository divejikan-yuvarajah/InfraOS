export function getAssessmentCopy(locale: AuthLocale): AssessmentCopy {
  return locale === "si" ? SI : locale === "ta" ? TA : EN;
}

/** Builds one localized sentence from a server factor key + code + params. Values are rendered as text only. */
export function factorSentence(copy: AssessmentCopy, factor: Pick<Factor, "key" | "code" | "params">): string {
  const table = copy.factor[factor.key];
  const template = table?.[factor.code] ?? table?.none ?? copy.component[factor.key] ?? factor.key;
  return fmt(template, factor.params);
}

export function mitigationSentence(copy: AssessmentCopy, m: Mitigation): string {
  return fmt(copy.factor.mitigation?.[m.key] ?? copy.lens.mitigation, m.params);
}
