export function getProjectCopy(locale: AuthLocale): ProjectCopy {
  if (locale === "si") return SI;
  if (locale === "ta") return TA;
  return EN;
}

export function projectListMessage(status: number, copy: ProjectCopy): string {
  if (status === 401 || status === 403) return copy.forbidden;
  return copy.unavailable;
}

export function projectReadMessage(status: number, copy: ProjectCopy): string {
  if (status === 404) return copy.notFound;
  return projectListMessage(status, copy);
}
